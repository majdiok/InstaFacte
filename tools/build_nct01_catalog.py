def validate(catalog: dict, remap: dict) -> None:
    nums = [a["number"] for a in catalog["accounts"]]
    assert len(nums) == len(set(nums)), "duplicate catalog numbers"
    assert "603" in nums and "6031" in nums and "6037" in nums
    assert "79" in nums and "7865" in nums
    assert "43652" in nums and "4477" not in nums
    assert "4371" in nums
    for a in catalog["accounts"]:
        if a["parent"]:
            assert a["number"].startswith(a["parent"].replace(".", "")[:1]) or a["number"].startswith(a["parent"])
            # dotted: 421.1 startswith 421
            if "." not in a["number"]:
                assert a["number"].startswith(a["parent"]), (a["number"], a["parent"])
    moves = [e for e in remap["entries"] if e["mode"] in ("move", "merge-into") and e["to"]]
    froms = [e["from"] for e in moves]
    # cycles 231/232 and 421/425 must exist
    assert any(e["from"] == "231" and e["to"] == "232" for e in moves)
    assert any(e["from"] == "232" and e["to"] == "231" for e in moves)
    assert any(e["from"] == "421" and e["to"] == "425" for e in moves)
    assert any(e["from"] == "425" and e["to"] == "421" for e in moves)
    assert any(e["from"] == "4477" and e["to"] == "43652" for e in moves)
    for p in remap["protectedPrefixes"]:
        assert p not in froms or any(e["from"] == p and e["to"] == p for e in remap["entries"])


