def account_class(num: str) -> int:
    return int(num[0])


def nature(num: str) -> int:
    """0 = Debit (actif / charge), 1 = Credit (passif / produit)."""
    cls = account_class(num)
    if num.startswith(("28", "29", "39", "49", "59")):
        return 1
    if num.startswith(("109", "259", "269", "529")):
        return 0
    if cls in (1, 7):
        return 1
    if cls in (2, 3, 6):
        return 0
    if num.startswith("409") or num.startswith("431") or num.startswith("4341") or num.startswith("4342"):
        return 0
    if num.startswith("4366"):
        return 0
    if num.startswith("419") or num.startswith("40") or num.startswith("42") or num.startswith("432"):
        return 1
    if num.startswith("4365") or num.startswith("4367") or num.startswith("4368") or num.startswith("437"):
        return 1
    if num.startswith("4343") or num.startswith("435"):
        return 1
    if num.startswith("41"):
        return 0
    if num.startswith("452") or num.startswith("455") or num.startswith("4411"):
        return 0
    if num.startswith("453") or num.startswith("447") or num.startswith("4412") or num.startswith("442"):
        return 1
    if num.startswith("50") or num.startswith("59"):
        return 1
    if cls == 5:
        return 0
    if cls == 4:
        return 1
    return 0


def parent_of(num: str, numbers: set[str]) -> str | None:
    # Dotted overlays: parent is the digit prefix before the dot.
    if "." in num:
        stem = num.split(".", 1)[0]
        if stem in numbers:
            return stem
    for i in range(len(num) - 1, 0, -1):
        cand = num[:i]
        if cand in numbers:
            return cand
    return None


def build_catalog() -> dict:
    seen: dict[str, str] = {}
    for n, lab in NCT_ACCOUNTS:
        seen[n] = lab
    overlay_nums = {n for n, _ in OVERLAY}
    for n, lab in OVERLAY:
        seen[n] = lab
    numbers = set(seen)
    accounts = []
    for n, lab in seen.items():
        par = parent_of(n, numbers - {n})
        accounts.append({
            "number": n,
            "label": lab,
            "accountClass": account_class(n),
            "parent": par,
            "natureType": nature(n),
            "level": len(n),
            "isSystem": True,
            "layer": "overlay" if n in overlay_nums else "nct01",
        })
    accounts.sort(key=lambda a: (a["accountClass"], a["number"]))
    return {
        "version": "nct01-v1",
        "source": "NCT 01 nomenclature (PDF) + NCT corrections 603/79/786x + overlay métier",
        "accounts": accounts,
    }


