    // ── Extournes (mouvements signés, v2.1) ─────────────────────────────────

    [Fact]
    public async Task GetPostedCashSaleVatByRateAsync_CrossPeriodReversal_OriginPeriodUnchangedAndReversalPeriodNegative()
    {
        var op = SeedCashSalesOperation(VatRate.Standard);
        var original = CashSaleEntry(1, new DateTime(2026, 3, 10), ht: 100m, vat: 19m, sourceOperationId: op.Id);
        var reversal = ReversalOf(original, 1, new DateTime(2026, 4, 5));
        original.MarkReversedBy(reversal.Id);

        await SeedAsync([op], [original, reversal]);

        var march = await _repository.GetPostedCashSaleVatByRateAsync(new DateTime(2026, 3, 1), new DateTime(2026, 3, 31));
        var april = await _repository.GetPostedCashSaleVatByRateAsync(new DateTime(2026, 4, 1), new DateTime(2026, 4, 30));

        // La période d'origine reste inchangée : positive malgré IsReversed=true sur l'origine.
        march.Should().ContainSingle();
        march[0].RatePercent.Should().Be(19);
        march[0].HtBase.Should().Be(100m);
        march[0].VatAmount.Should().Be(19m);

        // La période d'extourne porte un mouvement négatif.
        april.Should().ContainSingle();
        april[0].RatePercent.Should().Be(19);
        april[0].HtBase.Should().Be(-100m);
        april[0].VatAmount.Should().Be(-19m);

        (march[0].VatAmount + april[0].VatAmount).Should().Be(0m);
        (march[0].HtBase + april[0].HtBase).Should().Be(0m);
    }

    [Fact]
    public async Task GetPostedCashSaleVatByRateAsync_SamePeriodReversal_NetsToZero()
    {
        var op = SeedCashSalesOperation(VatRate.Standard);
        var original = CashSaleEntry(1, new DateTime(2026, 3, 5), ht: 100m, vat: 19m, sourceOperationId: op.Id);
        var reversal = ReversalOf(original, 2, new DateTime(2026, 3, 20));
        original.MarkReversedBy(reversal.Id);

        await SeedAsync([op], [original, reversal]);

        var result = await _repository.GetPostedCashSaleVatByRateAsync(new DateTime(2026, 3, 1), new DateTime(2026, 3, 31));

        result.Should().ContainSingle();
        result[0].RatePercent.Should().Be(19);
        result[0].HtBase.Should().Be(0m);
        result[0].VatAmount.Should().Be(0m);
    }

    [Fact]
    public async Task GetPostedCashSaleVatByRateAsync_ReversalOfReversal_IsIgnored()
    {
        var op = SeedCashSalesOperation(VatRate.Standard);
        var original = CashSaleEntry(1, new DateTime(2026, 3, 5), ht: 100m, vat: 19m, sourceOperationId: op.Id);
        var reversal1 = ReversalOf(original, 2, new DateTime(2026, 3, 20));
        original.MarkReversedBy(reversal1.Id);
        var reversal2 = ReversalOf(reversal1, 3, new DateTime(2026, 3, 25));
        reversal1.MarkReversedBy(reversal2.Id);

        await SeedAsync([op], [original, reversal1, reversal2]);

        var result = await _repository.GetPostedCashSaleVatByRateAsync(new DateTime(2026, 3, 1), new DateTime(2026, 3, 31));

        // reversal2 (extourne de reversal1, elle-même une extourne) est ignorée : seules
        // original + reversal1 contribuent, soit un net nul pour le taux.
        result.Should().ContainSingle();
        result[0].VatAmount.Should().Be(0m);
        result[0].HtBase.Should().Be(0m);
    }

