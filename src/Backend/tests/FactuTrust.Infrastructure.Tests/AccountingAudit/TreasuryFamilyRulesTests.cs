                new JournalLineInput("5411", "Caisse", 0m, 500m, null, ThirdPartyKind.None)));
            await db.SaveChangesAsync();
        }

        Assert.Empty(await EvaluateAsync(factory, new CashInWithoutDocumentAuditRule()));
    }
}
